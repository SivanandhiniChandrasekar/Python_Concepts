# Inheritance - Acquires attributes and behaviours from another class.
# A class which is derived from another class is called a child class or subclass. 
# The class from which the child class is derived is called a parent class or superclass. 
# The child class inherits all the properties and methods of the parent class. 
# The child class can also have its own properties and methods. 
# The child class can also override the properties and methods of the parent class.

